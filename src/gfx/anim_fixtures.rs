//! Embedded animation fixtures (test-only): a 3-frame clip of a red
//! bar stepping across a gradient, written by real encoders, plus one
//! video file whose only job is to be REFUSED.
//!
//! Regeneration (Pillow writes the GIF and the APNG; the `.mp4` is
//! muxed here so the refusal path has a structurally real subject):
//!
//! ```text
//! pip install pillow
//! python3 tools/make_anim_fixtures.py OUTDIR
//! ```
//!
//! The script is byte-reproducible: re-running it rewrites exactly the
//! arrays below.
//!
//! Ground truth: frame `i` paints the two columns `1 + 3i` and `2 + 3i`
//! red (240,30,30); every other pixel is `(20 + x*8, 20 + y*8, 120)`.
//! The bar is two pixels wide and never touches the canvas edge, so a
//! lossy container's smear cannot move where it reads.
//! [`bar_column`] and [`expected_rgb`] mirror that formula.

/// The red bar's left column in frame `i` (it is two wide).
pub fn bar_column(frame: usize) -> u32 {
    (1 + frame * 3) as u32
}

/// Ground truth for frame `frame` at `(x, y)`.
pub fn expected_rgb(frame: usize, x: u32, y: u32) -> (u8, u8, u8) {
    if x == bar_column(frame) || x == bar_column(frame) + 1 {
        (240, 30, 30)
    } else {
        ((20 + x * 8) as u8, (20 + y * 8) as u8, 120)
    }
}

