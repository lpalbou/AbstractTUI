//! Source provenance emitted by parsing and carried through typesetting.
//! Offsets are UTF-8 bytes in the original application-provided source.
use std::{ops::Range, rc::Rc};

/// The logical unit selected by an application, independent of soft wrapping.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum ContentKind {
    Word,
    Sentence,
    Paragraph,
    TableCell,
    CodeBlock,
    Span,
}

/// Local semantic identity supplied by the parser. Table body rows and columns
/// are zero based; a header cell has `row: None`. Code lines are one based.
#[derive(Clone, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub enum ContentContext {
    TableCell {
        row: Option<usize>,
        column: usize,
        header: Rc<str>,
    },
    Code {
        language: Rc<str>,
        lines: Range<usize>,
    },
}

#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) struct SourceRun {
    pub display: Range<usize>,
    pub source: Range<usize>,
}

#[derive(Clone, Debug)]
pub(crate) struct SourcePart {
    pub context: Option<Rc<ContentContext>>,
    pub scope: Range<usize>,
    pub kind: ContentKind,
    pub runs: Vec<SourceRun>,
}
impl SourcePart {
    pub(crate) fn literal(range: Range<usize>, kind: ContentKind) -> Self {
        Self {
            context: None,
            scope: range.clone(),
            kind,
            runs: vec![SourceRun {
                display: 0..range.len(),
                source: range,
            }],
        }
    }
    pub(crate) fn shifted(mut self, offset: usize, lines: usize) -> Self {
        self.scope.start += offset;
        self.scope.end += offset;
        for run in &mut self.runs {
            run.source.start += offset;
            run.source.end += offset;
        }
        if let Some(context) = &self.context {
            if let ContentContext::Code {
                language,
                lines: range,
            } = context.as_ref()
            {
                self.context = Some(Rc::new(ContentContext::Code {
                    language: language.clone(),
                    lines: range.start + lines..range.end + lines,
                }));
            }
        }
        self
    }
}

#[derive(Clone, Debug)]
pub(crate) struct SourceBlock {
    pub parts: Vec<SourcePart>,
}

/// One visible grapheme's provenance. Generated by the same fold as its pixels.
#[derive(Clone, Debug)]
pub(crate) struct SourceCell {
    pub context: Option<Rc<ContentContext>>,
    pub columns: Range<i32>,
    pub bytes: Range<usize>,
    pub scope: Range<usize>,
    pub kind: ContentKind,
}

#[derive(Clone, Debug)]
pub(crate) struct RowSource {
    pub source: Rc<str>,
    pub block: usize,
    pub cells: Vec<SourceCell>,
}
